async def fetch_context(
        collection_name: str,
        search_query: str,
        rpc_server_url:str
):
    """
    Fetches relevant context results from a remote vector search service via gRPC.

    This function connects to the specified gRPC server, sends a search request
    with the given collection name and query, and returns the search results.

    Args:
        collection_name (str): The name of the collection to search in.
        search_query (str): The query string to search for relevant context.
        rpc_server_url (str): The gRPC server URL (e.g., "localhost:50051").

    Returns:
        list: A list of search results returned by the vector service.

    Raises:
        grpc.aio.AioRpcError: If an RPC error occurs during the search.
    """

    async with grpc.aio.insecure_channel(rpc_server_url) as channel:
        stub = indexing_service_pb2_grpc.VectorServiceStub(channel)
        search_request = indexing_service_pb2.SearchRequest(
            collection_name=collection_name,
            query=search_query
        )
        try:
            search_response = await stub.Search(search_request)
            if search_response.results:
                logger.info(f"Success: Found {len(search_response.results)} result(s)")
            return search_response.results
        except grpc.aio.AioRpcError as e:
            logger.error(f"RPC error during Search: {e.code()} - {e.details()}")


async def fetch_assessments_by_framework(
        main_service_url: str,
        framework_id: int,
        exclude_assessment_id: int = None,
        limit: int = 5,
):
    """Fetches peer assessment IDs that belong to the same framework.

    Calls the main-service internal endpoint and returns a bounded list of
    assessment IDs (excluding the active assessment). Failures are logged and
    an empty list is returned, so chat retrieval degrades gracefully.
    """
    url = f"{main_service_url.rstrip('/')}/analysis/assessments-by-framework/{framework_id}"
    try:
        async with aiohttp.ClientSession() as session:
            async with session.get(url) as response:
                response.raise_for_status()
                data = await response.json()
    except Exception as e:  # noqa: BLE001 - cross-framework lookup is best-effort
        logger.error(f"Failed to fetch peer assessments for framework {framework_id}: {e}")
        return []

    peer_ids = []
    for item in data or []:
        assessment_id = item.get("assessment_id")
        if assessment_id is None or assessment_id == exclude_assessment_id:
            continue
        peer_ids.append(assessment_id)
    return peer_ids[:limit]


def format_translate_prompt(template: str, query_text: str, answer_text: str) -> list:
    """
    Constructs a prompt to check the language of the user's query and translate the answer if necessary.

    The prompt:
    - Asks the model to detect the language of the user's query.
    - If the query is not in English, translates the answer into the same language.
    - Outputs a structured JSON containing the final answer.

    Args:
        query_text (str): The user's original query.
        answer_text (str): The answer generated by the model before translation.

    Returns:
        list: A list containing a dictionary with the constructed prompt formatted for LLM input.
    """
    translate_prompt = template.format(
        query_text=query_text,
        answer_text=answer_text
    )
    return [{"role": "user", "content": translate_prompt}]
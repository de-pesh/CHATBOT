import logging
from typing import List, Dict

from fastapi import HTTPException, status

from app.stored_procedures import StoredProcedures
from app.models.auth import (
    UserRoleAssignmentPermissionCreate, 
    UserRoleAssignmentPermissionUpdate, 
    UserRoleAssignmentPermissionInDB,
    UserContextResponse,
    UserRoleDetail,
    UserPermissionDetail
)
from app.services.database_service import DatabaseService

logger = logging.getLogger(__name__)

class UserRoleAssignmentPermissionController:
    """
    Controller for managing user-role-permission assignments.

    This class encapsulates the business logic for creating, retrieving,
    updating, and deleting user-role-permission assignments, interacting with the database
    service to perform these actions.
    """

    def __init__(self, db_service: DatabaseService):
        self.db_service = db_service

    async def create_user_role_assignment_permission(self, urap_data: UserRoleAssignmentPermissionCreate, user_id: str) -> List[UserRoleAssignmentPermissionInDB]:
        """
        Creates new user-role-permission assignments.

        Args:
            urap_data (UserRoleAssignmentPermissionCreate): The data for the new assignments.
            user_id (str): The ID of the user creating the assignments.

        Returns:
            List[UserRoleAssignmentPermissionInDB]: A list of the created assignments' data.

        Raises:
            HTTPException: If any of the assignments cannot be created.
        """
        created_assignments = []
        try:
            for role_perm_id in urap_data.role_permission_assignment_ids:
                results = await self.db_service.call_procedure(
                    StoredProcedures.UPSERT_USER_ROLE_ASSIGNMENT_PERMISSION,
                    [
                        None,  # ID is auto-generated by the database
                        role_perm_id,
                        urap_data.user_id,
                        True,  # is_active is always True on creation
                        user_id
                    ]
                )
                if not results or not results[0]:
                    raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"Failed to create assignment for role_permission_assignment_id {role_perm_id}.")
                
                created_urap_id = results[0][0]['id']
                created_assignment = await self.get_all_user_role_assignment_permissions(urap_id=created_urap_id, page_number=1, page_size=1)
                created_assignments.extend(created_assignment)
            
            return created_assignments
        except HTTPException as e:
            logger.exception(f"Error creating user-role-permission assignments: {e}")
            raise e
        except Exception as e:
            logger.exception(f"Error creating user-role-permission assignments: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def get_all_user_role_assignment_permissions(
        self, 
        urap_id: int = None,
        role_permission_assignment_id: int = None,
        user_id: int = None, 
        is_active: bool = None,
        page_number: int = None, 
        page_size: int = None,
        count_required: bool = False
    ) -> List[UserRoleAssignmentPermissionInDB]:
        """
        Retrieves user-role-permission assignments with pagination and optional filtering.

        Args:
            urap_id (int): Optional ID of the specific assignment.
            role_permission_assignment_id (int): Optional Role-Permission Assignment ID.
            user_id (int): Optional User ID filter.
            is_active (bool): Optional active status filter.
            page_number (int): The page number.
            page_size (int): The page size.
            count_required (bool): If True, returns dict with count and results.

        Returns:
            List[UserRoleAssignmentPermissionInDB] or dict: The data list or the paginated response.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.FILTER_USER_ROLE_ASSIGNMENT_PERMISSIONS,
                [
                    urap_id,                        # id
                    role_permission_assignment_id,  # role_permission_assignment_id
                    user_id,                        # user_id
                    is_active,                      # is_active
                    page_number,
                    page_size
                ]
            )
            
            # Handle empty results
            if not results or not results[0]:
                return {"total_count": 0, "results": []} if count_required else []
            
            # Parse Data
            assignments_in_db = [UserRoleAssignmentPermissionInDB(**urap_data) for urap_data in results[0]]
            
            # Handle Count Requirement
            if count_required:
                if not results or len(results) < 2 or not results[1] or not results[1][0]:
                    return {"total_count": 0, "results": []}
                
                count = results[1][0]["total_count"]
                return {"total_count": count, "results": assignments_in_db}
                
            return assignments_in_db

        except Exception as e:
            logger.exception(f"Error retrieving user-role-permission assignments: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def get_user_roles_and_permissions_details(self, user_id: int) -> UserContextResponse:
        """
        Retrieves all active roles and their specific active permissions for a user.
        Groups the flat DB result into a hierarchical structure.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.GET_USER_ROLES_AND_PERMISSIONS,
                [user_id]
            )

            # If no results found, return empty structure
            if not results or not results[0]:
                return UserContextResponse(user_id=user_id, roles=[])

            # Data Transformation: Group Permissions by Role
            roles_map: Dict[int, UserRoleDetail] = {}

            for row in results[0]:
                role_id = row['role_id']
                
                # If role not yet in map, initialize it
                if role_id not in roles_map:
                    roles_map[role_id] = UserRoleDetail(
                        id=role_id,
                        name=row['role_name'],
                        description=row['role_description'],
                        permissions=[]
                    )
                
                # Append permission details to the specific role
                # Note: This logic assumes valid data. If permission_id is None (orphan role), handle accordingly.
                if row.get('permission_id'):
                    permission_detail = UserPermissionDetail(
                        id=row['permission_id'],
                        name=row['permission_name'],
                        description=row['permission_description']
                    )
                    roles_map[role_id].permissions.append(permission_detail)

            # Convert map values to list
            return UserContextResponse(user_id=user_id, roles=list(roles_map.values()))

        except Exception as e:
            logger.exception(f"Error retrieving user context for user {user_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def update_user_role_assignment_permission(self, user_id: int, urap_data: UserRoleAssignmentPermissionUpdate, updated_by_user: str) -> List[UserRoleAssignmentPermissionInDB]:
        """
        Synchronizes the set of role-permission assignments for a user.

        Args:
            user_id (int): The ID of the user whose assignments are being synchronized.
            urap_data (UserRoleAssignmentPermissionUpdate): The data containing the definitive list of active assignments.
            updated_by_user (str): The ID of the user performing the update.

        Returns:
            List[UserRoleAssignmentPermissionInDB]: The final list of active assignments for the user.
        """
        try:
            incoming_ids = set(urap_data.role_permission_assignment_ids)
            
            # 1. Get all existing assignments for the user from the database
            all_db_assignments = await self.get_all_user_role_assignment_permissions(user_id = user_id)
            db_assignments_map = {a.role_permission_assignment_id: a for a in all_db_assignments}

            # 2. Process assignments that should be active
            for rpa_id in incoming_ids:
                assignment = db_assignments_map.get(rpa_id)
                if not assignment:
                    # It's a new assignment, create it as active.
                    await self.db_service.call_procedure(
                        StoredProcedures.UPSERT_USER_ROLE_ASSIGNMENT_PERMISSION,
                        [None, rpa_id, user_id, True, updated_by_user]
                    )
                elif not assignment.is_active:
                    # It exists but is inactive, so activate it.
                    await self.db_service.call_procedure(
                        StoredProcedures.UPSERT_USER_ROLE_ASSIGNMENT_PERMISSION,
                        [assignment.id, rpa_id, user_id, True, updated_by_user]
                    )

            # 3. Process assignments that should be inactive
            for rpa_id, assignment in db_assignments_map.items():
                if rpa_id not in incoming_ids and assignment.is_active:
                    # This existing active assignment is not in the incoming list, so deactivate it.
                    await self.db_service.call_procedure(
                        StoredProcedures.UPSERT_USER_ROLE_ASSIGNMENT_PERMISSION,
                        [assignment.id, rpa_id, user_id, False, updated_by_user]
                    )

            # 4. Return the final state of active assignments for the user
            final_assignments = await self.get_all_user_role_assignment_permissions(user_id = user_id)
            return [a for a in final_assignments if a.is_active]

        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error synchronizing user-role-permission assignments for user {user_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred during synchronization: {e}")

    async def delete_user_role_assignment_permission(self, urap_id: str, user_id: str) -> dict:
        """
        Deletes a user-role-permission assignment by its ID.

        Args:
            urap_id (str): The unique identifier of the assignment to delete.
            user_id (str): The ID of the user deleting the assignment.

        Returns:
            dict: A confirmation message.

        Raises:
            HTTPException: If the assignment is not found or cannot be deleted.
        """
        try:
            await self.get_all_user_role_assignment_permissions(urap_id=urap_id, page_number=1, page_size=1)

            results = await self.db_service.call_procedure(
                StoredProcedures.DELETE_USER_ROLE_ASSIGNMENT_PERMISSION,
                [urap_id, user_id]
            )
            if not results or not results[0] or results[0][0].get("success", False) == False:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to delete user-role-permission assignment.")
            
            return {"message": f"User-role-permission assignment {urap_id} deleted successfully."}
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error deleting user-role-permission assignment {urap_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

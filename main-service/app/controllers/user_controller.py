import logging
from typing import List, Optional

from fastapi import HTTPException, status

from app.core.stored_procedures import StoredProcedures
from app.models.auth import UserCreate, UserUpdate, UserInDB
from app.services.database_service import DatabaseService
from app.core.security import get_password_hash

logger = logging.getLogger(__name__)


def _sanitize_exception_detail(exc: Exception) -> str:
    """Return a client-safe error message without DB numeric codes."""
    args = getattr(exc, "args", None)
    if isinstance(args, tuple) and len(args) >= 2 and isinstance(args[0], int):
        if isinstance(args[1], str) and args[1].strip():
            return args[1]
    message = str(exc)
    return message if message else "Unexpected error"

class UserController:
    """
    Controller for managing user-related operations.

    This class encapsulates the business logic for creating, retrieving,
    updating, and deleting users, interacting with the database
    service to perform these actions.
    """

    def __init__(self, db_service: DatabaseService):
        self.db_service = db_service

    async def create_user(self, user_data: UserCreate, created_by: str) -> List[UserInDB]:
        """
        Creates a new user.

        Args:
            user_data (UserCreate): The data for the new user.
            created_by (str): The email of the user creating the user.

        Returns:
            List[UserInDB]: The created user's data including their generated ID.

        Raises:
            HTTPException: If the user cannot be created.
        """
        try:
            hashed_password = get_password_hash(user_data.password)
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_USER,
                [
                    None,  # ID is auto-generated by the database
                    user_data.first_name,
                    user_data.last_name,
                    user_data.email,
                    hashed_password,
                    user_data.organization_id,
                    True, # is_active is True by default
                    created_by
                ]
            )
            if not results or not results[0] or not results[0][0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to create user.")
            
            user_id = results[0][0]['id']
            return await self.get_all_users(user_id=user_id, page_number=1, page_size=1)
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error creating user: {e}")
            detail_message = _sanitize_exception_detail(e)
            raise HTTPException(
                status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
                detail=f"An error occurred: {detail_message}"
            )

    async def get_all_users(
        self, 
        user_id: int = None, 
        first_name: str = None,
        last_name: str = None,
        email: str = None,
        organization_id: int = None,
        is_active: bool = None,
        page_number: int = None, 
        page_size: int = None,
        count_required: bool = False,
        role_name: Optional[str] = None
    ) -> List[UserInDB]:
        """
        Retrieves users with pagination and optional filtering.

        Args:
            user_id (int): Optional User ID filter.
            first_name (str): Optional first name filter.
            last_name (str): Optional last name filter.
            email (str): Optional email filter.
            organization_id (int): Optional organization ID filter.
            is_active (bool): Optional active status filter.
            page_number (int): The page number.
            page_size (int): The page size.
            count_required (bool): If True, returns dict with count and results.

        Returns:
            List[UserInDB] or dict: The list of users or the paginated response wrapper.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.FILTER_USERS_USER_MANAGEMENT,
                [
                    user_id,            # id
                    first_name,         # first_name
                    last_name,          # last_name
                    email,              # email
                    organization_id,    # organization_id
                    is_active,          # is_active
                    page_number,
                    page_size,
                    role_name
                ]
            )
            
            # Handle empty results
            if not results or not results[0]:
                return {"total_count": 0, "results": []} if count_required else []

            users_in_db = [UserInDB(**user_data) for user_data in results[0]]
            
            # Handle Count Requirement
            if count_required:
                # if not results or len(results) < 2 or not results[1] or not results[1][0]:
                #     return {"total_count": 0, "results": []}
                
                # count = results[1][0]["total_count"]
                count_row = None
                for result_set in results[1:]:
                    if result_set and len(result_set)>0:
                        count_row = result_set[0]
                        break
                
                if count_row is None:
                    return {"total_count": len(users_in_db), "results": users_in_db}

                if isinstance(count_row, dict):
                    count = None
                    for key in ("total_count", "total_records", "count"):
                        if key in count_row and count_row[key] is not None:
                            count = count_row[key]
                            break
                    if count is None and len(count_row) == 1:
                        # Fallback when DB connector returns an unexpected alias.
                        count = next(iter(count_row.values()))
                elif isinstance(count_row, (list, tuple)) and len(count_row) > 0:
                    count = count_row[0]
                else:
                    count = 0

                try:
                    count = int(count) if count is not None else 0
                except (TypeError, ValueError):
                    count = 0

                
                return {"total_count": count, "results": users_in_db}
                
            return users_in_db

        except Exception as e:
            logger.exception(f"Error retrieving users: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def update_user(self, user_id: int, user_data: UserUpdate, updated_by: str) -> List[UserInDB]:
        """
        Updates an existing user.

        Args:
            user_id (str): The ID of the user to update.
            user_data (UserUpdate): The update data for the user.

        Returns:
            List[UserInDB]: The updated user's data.

        Raises:
            HTTPException: If the user is not found or cannot be updated.
        """
        existing_user = await self.get_all_users(user_id=user_id, page_number=1, page_size=1)

        update_params = {
            "id": user_id,
            "first_name": user_data.first_name if user_data.first_name is not None else existing_user[0].first_name,
            "last_name": user_data.last_name if user_data.last_name is not None else existing_user[0].last_name,
            "email": user_data.email if user_data.email is not None else existing_user[0].email,
            "hashed_password": existing_user[0].hashed_password,
            "organization_id": user_data.organization_id if user_data.organization_id is not None else existing_user[0].organization_id,
            "is_active": user_data.is_active if user_data.is_active is not None else existing_user[0].is_active,
            "updated_by": updated_by
        }

        try:
            await self.db_service.call_procedure(StoredProcedures.UPSERT_USER, list(update_params.values()))
            
            return await self.get_all_users(user_id=user_id, page_number=1, page_size=1)

        except Exception as e:
            logger.exception(f"Error updating user {user_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def delete_user(self, user_id: int, deleted_by: str) -> dict:
        """
        Deletes a user by their ID.

        Args:
            user_id (int): The unique identifier of the user to delete.
            deleted_by (str): The email of the user deleting the user.

        Returns:
            dict: A confirmation message.

        Raises:
            HTTPException: If the user is not found or cannot be deleted.
        """
        try:
            await self.get_all_users(user_id=user_id, page_number=1, page_size=1)

            await self.db_service.call_procedure(
                StoredProcedures.DELETE_USER,
                [user_id, deleted_by]
            )
            
            return {"message": f"User {user_id} deleted successfully."}
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error deleting user {user_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

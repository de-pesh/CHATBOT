import logging
from typing import List

from fastapi import HTTPException, status

from app.core.stored_procedures import StoredProcedures
from app.models.files import AssetTypeCreate, AssetTypeUpdate, AssetTypeInDB
from app.services.database_service import DatabaseService


logger = logging.getLogger(__name__)


class AssetTypeController:
    """
    Controller for managing asset type related operations.

    This class encapsulates the business logic for creating, retrieving,
    updating, and deleting asset types, interacting with the database
    service to perform these actions.
    """

    def __init__(self, db_service: DatabaseService):
        self.db_service = db_service


    async def create_asset_type(self, asset_type_data: AssetTypeCreate, created_by: str) -> List[AssetTypeInDB]:
        """
        Creates new asset types.

        Args:
            asset_type_data (AssetTypeCreate): The data for the new asset types.

        Returns:
            AssetTypeInDB: The list of asset type's for the organization ID.

        Raises:
            HTTPException: If the asset type cannot be created.
        """
        try:
            response = []
            for asset_type in asset_type_data.data:
                results = await self.db_service.call_procedure(
                    StoredProcedures.UPSERT_ASSET_TYPE,
                    [
                        None,  # ID is auto-generated by the database
                        asset_type.name,
                        asset_type.description,
                        asset_type_data.organization_id,
                        True,
                        created_by
                    ]
                )
                if not results or not results[0]:
                    raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to create asset type.")
                
                response += (await self.get_asset_types(results[0][0].get("id")))

            return response
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error creating asset type: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")


    async def get_asset_types(self, asset_type_id: int = None, org_id: int = None, page_number: int = None, page_size: int = None, count_required: bool = False) -> List[AssetTypeInDB]:
        """
        Retrieves all asset types of a organization.

        Returns:
            List[AssetTypeInDB]: A list of all asset types.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.FILTER_ASSET_TYPES,
                [asset_type_id, None, org_id, True, page_number, page_size]
            )
            if not results or not results[0]:
                return {"total_count": 0, "results": []} if count_required else []
            
            response = [AssetTypeInDB(**asset_type_data) for asset_type_data in results[0]]

            if count_required:
                if not results or not results[1] or not results[1][0]:
                    return {"total_count": 0, "results": []}
                count = results[1][0]["total_count"]
                return {"total_count": count, "results": response}
            return response
        except Exception as e:
            logger.exception(f"Error retrieving all asset types: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")


    async def update_asset_type(self, asset_type_id: int, asset_type_data: AssetTypeUpdate, updated_by: str) -> AssetTypeInDB:
        """
        Updates an existing asset type.

        Args:
            asset_type_id (str): The ID of the asset type to update.
            asset_type_data (AssetTypeUpdate): The update data for the asset type.

        Returns:
            AssetTypeInDB: The updated asset type's data.

        Raises:
            HTTPException: If the asset type is not found or cannot be updated.
        """
        existing_asset_type = await self.get_asset_types(asset_type_id)

        update_params = {
            "name": asset_type_data.name if asset_type_data.name is not None else existing_asset_type.name,
            "description": asset_type_data.description if asset_type_data.description is not None else existing_asset_type.description,
            "updated_by": updated_by
        }

        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_ASSET_TYPE,
                [
                    asset_type_id,
                    update_params["name"],
                    update_params["description"],
                    None,
                    None, # is_active is not updated here
                    update_params["updated_by"]
                ]
            )
            if not results or not results[0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to update asset type.")
            
            return await self.get_asset_types(asset_type_id=asset_type_id)
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error updating asset type {asset_type_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")


    async def delete_asset_type(self, asset_type_id: int, user_id: str) -> None:
        """
        Deletes an asset type by its ID.

        Args:
            asset_type_id (str): The unique identifier of the asset type to delete.

        Returns:
            dict: A confirmation message.

        Raises:
            HTTPException: If the asset type is not found or cannot be deleted.
        """
        try:
            await self.get_asset_types(asset_type_id=asset_type_id)

            await self.db_service.call_procedure(
                StoredProcedures.DELETE_ASSET_TYPE,
                [asset_type_id, user_id]
            )
            
            return None
        except HTTPException:
            raise # re-raise
        except Exception as e:
            logger.exception(f"Error deleting asset type {asset_type_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

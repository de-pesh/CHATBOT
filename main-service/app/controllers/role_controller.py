import logging
from typing import List

from fastapi import HTTPException, status

from app.core.stored_procedures import StoredProcedures
from app.models.auth import RoleCreate, RoleUpdate, RoleInDB
from app.services.database_service import DatabaseService

logger = logging.getLogger(__name__)

class RoleController:
    """
    Controller for managing role-related operations.

    This class encapsulates the business logic for creating, retrieving,
    updating, and deleting roles, interacting with the database
    service to perform these actions.
    """

    def __init__(self, db_service: DatabaseService):
        self.db_service = db_service

    async def create_role(self, role_data: RoleCreate, user_id: str) -> List[RoleInDB]:
        """
        Creates a new role.

        Args:
            role_data (RoleCreate): The data for the new role.
            user_id (str): The ID of the user creating the role.

        Returns:
            List[RoleInDB]: The created role's data including its generated ID.

        Raises:
            HTTPException: If the role cannot be created.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_ROLE,
                [
                    None,  # ID is auto-generated by the database
                    role_data.name,
                    role_data.description,
                    True,  # is_active is always True on creation
                    user_id
                ]
            )
            if not results or not results[0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to create role.")
            
            created_role_id = results[0][0]['id']
            return await self.get_all_roles(role_id=created_role_id, page_number=1, page_size=1)
        except Exception as e:
            logger.exception(f"Error creating role: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def get_all_roles(
        self, 
        role_id: int = None, 
        name: str = None, 
        is_active: bool = None, 
        page_number: int = None, 
        page_size: int = None,
        count_required: bool = False
    ) -> List[RoleInDB]:
        """
        Retrieves roles with pagination and optional filtering.

        Args:
            role_id (int): Optional Role ID filter.
            name (str): Optional name filter (fuzzy match).
            is_active (bool): Optional active status filter.
            page_number (int): The page number.
            page_size (int): The page size.
            count_required (bool): If True, returns dict with count and results.

        Returns:
            List[RoleInDB] or dict: The list of roles or the paginated response wrapper.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.FILTER_ROLES,
                [
                    role_id,    # id
                    name,       # name
                    is_active,  # is_active
                    page_number,
                    page_size
                ]
            )
            
            # Handle empty results
            if not results or not results[0]:
                return {"total_count": 0, "results": []} if count_required else []
            
            # Parse Data
            roles_in_db = [RoleInDB(**role_data) for role_data in results[0]]
            
            # Handle Count Requirement
            if count_required:
                if not results or len(results) < 2 or not results[1] or not results[1][0]:
                    return {"total_count": 0, "results": []}
                
                count = results[1][0]["total_count"]
                return {"total_count": count, "results": roles_in_db}
                
            return roles_in_db

        except Exception as e:
            logger.exception(f"Error retrieving roles: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def update_role(self, role_id: str, role_data: RoleUpdate, user_id: str) -> List[RoleInDB]:
        """
        Updates an existing role.

        Args:
            role_id (str): The ID of the role to update.
            role_data (RoleUpdate): The update data for the role.
            user_id (str): The ID of the user updating the role.

        Returns:
            List[RoleInDB]: The updated role's data.

        Raises:
            HTTPException: If the role is not found or cannot be updated.
        """
        existing_role = await self.get_all_roles(role_id=role_id, page_number=1, page_size=1)

        update_params = {
            "id": role_id,
            "name": role_data.name if role_data.name is not None else existing_role[0].name,
            "description": role_data.description if role_data.description is not None else existing_role[0].description,
            "is_active": role_data.is_active if role_data.is_active is not None else existing_role[0].is_active,
            "updated_by": user_id
        }

        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_ROLE,
                [
                    update_params["id"],
                    update_params["name"],
                    update_params["description"],
                    update_params["is_active"],
                    update_params["updated_by"]
                ]
            )
            if not results or not results[0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to update role.")
            
            return await self.get_all_roles(role_id=role_id, page_number=1, page_size=1)
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error updating role {role_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def delete_role(self, role_id: str, user_id: str) -> dict:
        """
        Deletes a role by its ID.

        Args:
            role_id (str): The unique identifier of the role to delete.
            user_id (str): The ID of the user performing the deletion.

        Returns:
            dict: A confirmation message.

        Raises:
            HTTPException: If the role is not found or cannot be deleted.
        """
        try:
            await self.get_all_roles(role_id=role_id, page_number=1, page_size=1)

            results = await self.db_service.call_procedure(
                StoredProcedures.DELETE_ROLE,
                [role_id, user_id]
            )
            if not results or not results[0] or results[0][0].get("success", False) == False:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to delete role.")
            
            return {"message": f"Role {role_id} deleted successfully."}
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error deleting role {role_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

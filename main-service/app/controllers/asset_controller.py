import logging
from typing import List, Optional

from fastapi import HTTPException, status

from app.core.stored_procedures import StoredProcedures
from app.models.files import AssetCreate, AssetUpdate, AssetInDB
from app.services.database_service import DatabaseService

logger = logging.getLogger(__name__)

class AssetController:
    """
    Controller for managing asset-related operations.

    This class encapsulates the business logic for creating, retrieving,
    updating, and deleting assets, interacting with the database
    service to perform these actions.
    """

    def __init__(self, db_service: DatabaseService):
        self.db_service = db_service


    async def create_asset(self, asset_data: AssetCreate, created_by: str) -> List[AssetInDB]:
        """
        Creates new assets.

        Args:
            asset_data (AssetCreate): The data for the new assets.

        Returns:
            List[AssetInDB]: The list of created asset's data including its generated ID.

        Raises:
            HTTPException: If the asset cannot be created.
        """
        try:
            response = []
            for asset in asset_data.data:
                results = await self.db_service.call_procedure(
                    StoredProcedures.UPSERT_ASSET,
                    [
                        None,  # ID is auto-generated by the database
                        asset.name,
                        asset.description,
                        asset.asset_type_id,
                        True,  # is_active
                        created_by
                    ]
                )
                if not results or not results[0]:
                    raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to create asset.")
            
                asset_id = results[0][0]['id']
                response += (await self.get_all_assets(asset_id=asset_id, page_number=1, page_size=1))
            return response
        except Exception as e:
            logger.exception(f"Error creating asset: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")


    async def get_all_assets(
        self,
        asset_id: int = None,
        org_id: int = None,
        asset_type_id: Optional[int] = None,
        page_number: Optional[int] = None,
        page_size: Optional[int] = None,
        count_required: bool = False
    ) -> List[AssetInDB]:
        """
        Retrieves all assets for a organization.

        Returns:
            List[AssetInDB]: A list of all assets by organization.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.FILTER_ASSETS,
                [asset_id, org_id, None, asset_type_id, True, page_number, page_size],
            )
            if not results or not results[0]:
                return {"total_count": 0, "results": []} if count_required else []
            
            response = [AssetInDB(**asset_data) for asset_data in results[0]]

            if count_required:
                if not results or not results[1] or not results[1][0]:
                    return {"total_count": 0, "results": []}
                count = results[1][0]["total_count"]
                return {"total_count": count, "results": response}
            
            return response
        except Exception as e:
            logger.exception(f"Error retrieving all assets: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")
        

    async def update_asset(self, asset_id: int, asset_data: AssetUpdate, updated_by: str) -> AssetInDB:
        """
        Updates an existing asset.

        Args:
            asset_id (str): The ID of the asset to update.
            asset_data (AssetUpdate): The update data for the asset.

        Returns:
            AssetInDB: The updated asset's data.

        Raises:
            HTTPException: If the asset is not found or cannot be updated.
        """
        existing_asset = await self.get_all_assets(asset_id)

        update_params = {
            "id": asset_id,
            "name": asset_data.name if asset_data.name is not None else existing_asset.name,
            "description": asset_data.description if asset_data.description is not None else existing_asset.description,
            "asset_type_id": asset_data.asset_type_id if asset_data.asset_type_id is not None else existing_asset.asset_type_id,
            "updated_by": updated_by
        }

        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_ASSET,
                [
                    update_params["id"],
                    update_params["name"],
                    update_params["description"],
                    update_params["asset_type_id"],
                    None, # is_active is not updated here
                    update_params["updated_by"]
                ]
            )
            if not results or not results[0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to update asset.")
            
            return await self.get_all_assets(asset_id)
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error updating asset {asset_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")


    async def delete_asset(self, asset_id: int, user_id: str) -> None:
        """
        Deletes an asset by its ID.

        Args:
            asset_id (str): The unique identifier of the asset to delete.

        Returns:
            dict: A confirmation message.

        Raises:
            HTTPException: If the asset is not found or cannot be deleted.
        """
        try:
            await self.get_all_assets(asset_id)

            await self.db_service.call_procedure(
                StoredProcedures.DELETE_ASSET,
                [asset_id, user_id]
            )
            
            return None
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error deleting asset {asset_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

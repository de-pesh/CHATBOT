import logging
from typing import List

from fastapi import HTTPException, status

from app.core.stored_procedures import StoredProcedures
from app.models.auth import PermissionCreate, PermissionUpdate, PermissionInDB
from app.services.database_service import DatabaseService

logger = logging.getLogger(__name__)

class PermissionController:
    """
    Controller for managing permission-related operations.

    This class encapsulates the business logic for creating, retrieving,
    updating, and deleting permissions, interacting with the database
    service to perform these actions.
    """

    def __init__(self, db_service: DatabaseService):
        self.db_service = db_service

    async def create_permission(self, permission_data: PermissionCreate, user_id: str) -> List[PermissionInDB]:
        """
        Creates a new permission.

        Args:
            permission_data (PermissionCreate): The data for the new permission.
            user_id (str): The ID of the user creating the permission.

        Returns:
            List[PermissionInDB]: The created permission's data including its generated ID.

        Raises:
            HTTPException: If the permission cannot be created.
        """
        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_PERMISSION,
                [
                    None,  # ID is auto-generated by the database
                    permission_data.name,
                    permission_data.description,
                    True,  # is_active is always True on creation
                    user_id
                ]
            )
            if not results or not results[0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to create permission.")
            
            created_permission_id = results[0][0]['id']
            return await self.get_all_permissions(permission_id=created_permission_id, page_number=1, page_size=1)
        except Exception as e:
            logger.exception(f"Error creating permission: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def get_all_permissions(
        self, 
        permission_id: int = None, 
        page_number: int = None, 
        page_size: int = None, 
        is_active: bool = None, 
        count_required: bool = False
    ) -> List[PermissionInDB]:
        """
        Retrieves permissions with pagination and optional filtering.

        Args:
            permission_id (int): Optional ID filter.
            page_number (int): The page number to retrieve.
            page_size (int): The number of permissions per page.
            is_active (bool): Optional filter for active status.
            count_required (bool): Whether to return the total count wrapper or just the list.

        Returns:
            List[PermissionInDB] or dict: List of permissions or Dict with count and results.
        """
        try:
            # Call the Stored Procedure
            results = await self.db_service.call_procedure(
                StoredProcedures.FILTER_PERMISSIONS,
                [
                    permission_id,  # id
                    None,           # name
                    is_active,      # is_active
                    page_number,
                    page_size
                ]
            )
            
            # Handle empty results
            if not results or not results[0]:
                return {"total_count": 0, "results": []} if count_required else []
            
            # Parse the actual data (first result set)
            permissions_in_db = [PermissionInDB(**perm_data) for perm_data in results[0]]
            
            # If count is required, parse the second result set
            if count_required:
                if not results or len(results) < 2 or not results[1] or not results[1][0]:
                    # Fallback if SP doesn't return count
                    return {"total_count": 0, "results": []}
                
                count = results[1][0]["total_count"] # Mapping to 'total_count' from SP
                return {"total_count": count, "results": permissions_in_db}
            
            return permissions_in_db

        except Exception as e:
            logger.exception(f"Error retrieving permissions: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")


    async def update_permission(self, permission_id: str, permission_data: PermissionUpdate, user_id: str) -> List[PermissionInDB]:
        """
        Updates an existing permission.

        Args:
            permission_id (str): The ID of the permission to update.
            permission_data (PermissionUpdate): The update data for the permission.
            user_id (str): The ID of the user updating the permission.

        Returns:
            List[PermissionInDB]: The updated permission's data.

        Raises:
            HTTPException: If the permission is not found or cannot be updated.
        """
        existing_permission = await self.get_all_permissions(permission_id=permission_id, page_number=1, page_size=1)

        update_params = {
            "id": permission_id,
            "name": permission_data.name if permission_data.name is not None else existing_permission[0].name,
            "description": permission_data.description if permission_data.description is not None else existing_permission[0].description,
            "is_active": permission_data.is_active if permission_data.is_active is not None else existing_permission[0].is_active,
            "updated_by": user_id
        }

        try:
            results = await self.db_service.call_procedure(
                StoredProcedures.UPSERT_PERMISSION,
                [
                    update_params["id"],
                    update_params["name"],
                    update_params["description"],
                    update_params["is_active"],
                    update_params["updated_by"]
                ]
            )
            if not results or not results[0]:
                raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail="Failed to update permission.")
            
            return await self.get_all_permissions(permission_id=permission_id, page_number=1, page_size=1)
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error updating permission {permission_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")

    async def delete_permission(self, permission_id: str, user_id: str) -> None:
        """
        Deletes a permission by its ID.

        Args:
            permission_id (str): The unique identifier of the permission to delete.
            user_id (str): The ID of the user deleting the permission.
        """
        try:
            await self.get_all_permissions(permission_id=permission_id, page_number=1, page_size=1)

            await self.db_service.call_procedure(
                StoredProcedures.DELETE_PERMISSION,
                [permission_id, user_id]
            )
        except HTTPException:
            raise
        except Exception as e:
            logger.exception(f"Error deleting permission {permission_id}: {e}")
            raise HTTPException(status_code=status.HTTP_500_INTERNAL_SERVER_ERROR, detail=f"An error occurred: {e}")
